import { formatNum, loadData } from "@/lib/data";
import { Badge, Card, PageHeader, Provenance, ScoreBadge, Section, SeverityBadge, Stat } from "@/components/ui";
import DatasetChecker from "@/components/DatasetChecker";

const THRESHOLD_KEYS = [
  "missing_rate_warn",
  "missing_rate_fail",
  "duplicate_rate_warn",
  "duplicate_rate_fail",
  "conflict_rate_warn",
  "conflict_rate_fail",
  "imbalance_ratio_warn",
  "imbalance_ratio_fail",
  "label_noise_warn",
  "label_noise_fail",
  "label_noise_certainty",
  "leakage_overlap_fail",
  "leakage_single_feature_accuracy",
  "outlier_rate_warn",
  "outlier_rate_fail",
  "adversarial_auc_warn",
  "adversarial_auc_fail",
  "min_samples_per_feature",
  "min_samples_per_class",
];

export default function RubricsPage() {
  const datasetRubric = loadData("rubric_dataset.json");
  const modelRubric = loadData("rubric_model.json");
  const validation = loadData("rubric_validation.json");
  const config = loadData("rubric_config.json");

  const summary = datasetRubric.summary;
  const rows = validation.rows as any[];
  const noiseRows = rows.filter((r) => r.label_noise);

  return (
    <div>
      <PageHeader
        title="Automated evaluation rubrics"
        lead={
          <>
            Every threshold and weight lives in <code>configs/rubrics.yaml</code>. Dataset-quality checks cover
            missingness, constant columns, duplicates, conflicting labels, imbalance, confident-learning-style
            label noise, leakage, outliers, covariate shift, redundancy, low information and sample adequacy.
            Model-correctness checks cover baseline significance, generalization gap, stability, calibration,
            per-class recall, robustness, prediction sanity, reproducibility and efficiency. The validation table
            below is generated by running the rubric on datasets with <em>planted</em> defects.
          </>
        }
      />

      <div className="mt-6 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
        <Stat
          label="Overall rubric"
          value={`${formatNum(summary?.overall_score, 1)}`}
          hint={`grade ${summary?.overall_grade}`}
          tone={summary?.overall_score >= 85 ? "good" : "warn"}
        />
        <Stat
          label="Dataset-quality mean"
          value={formatNum(summary?.dataset_quality_score, 1)}
          hint={`${datasetRubric.datasets?.length ?? 0} datasets`}
        />
        <Stat
          label="Model-correctness mean"
          value={formatNum(summary?.model_correctness_score, 1)}
          hint={`${modelRubric.models?.length ?? 0} dataset/model pairs`}
        />
        <Stat
          label="Validation detection"
          value={`${validation.summary?.n_detected}/${validation.summary?.n_defect_datasets}`}
          hint={`clean dataset ${formatNum(validation.summary?.clean_score, 1)} (${validation.summary?.clean_grade})`}
          tone={validation.summary?.detection_rate === 1 ? "good" : "warn"}
        />
      </div>

      <Section
        title="Rubric validation on planted defects"
        subtitle="Detection means the responsible check returned warn or fail. Label-noise estimates are compared with the planted rate."
      >
        <Card className="overflow-x-auto p-0">
          <table className="data w-full text-sm">
            <thead className="bg-slate-50">
              <tr>
                <th>Defect</th>
                <th>Expected check</th>
                <th>Severity</th>
                <th>Detected</th>
                <th>Score</th>
                <th>Evidence</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => {
                const ev = r.evidence ?? {};
                const noise = r.label_noise;
                return (
                  <tr key={r.defect}>
                    <td className="font-medium text-slate-900">{r.defect}</td>
                    <td className="text-slate-600">{r.expected_check ?? "—"}</td>
                    <td>
                      <SeverityBadge severity={r.actual_severity} />
                    </td>
                    <td>
                      {r.detected === null ? "—" : r.detected ? <Badge tone="green">yes</Badge> : <Badge tone="rose">no</Badge>}
                    </td>
                    <td className="tabular">{formatNum(r.overall_score, 1)}</td>
                    <td className="max-w-[32rem] whitespace-normal text-xs text-slate-500">
                      {noise
                        ? `planted ${(noise.planted_rate * 100).toFixed(0)}%, estimate ${(noise.estimated_rate * 100).toFixed(
                            1,
                          )}% · precision ${noise.identification.precision.toFixed(2)}, recall ${noise.identification.recall.toFixed(2)}`
                        : Object.entries(ev)
                            .slice(0, 4)
                            .map(([k, v]) => `${k}=${typeof v === "number" ? Number(v).toPrecision(4) : String(v)}`)
                            .join(" · ")}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </Card>
        <div className="mt-3 grid gap-3 sm:grid-cols-3">
          <Card>
            <div className="text-xs uppercase tracking-wide text-slate-500">Label-noise tolerance</div>
            <div className="mt-1 text-sm text-slate-700">
              ±{formatNum(validation.summary?.label_noise_tolerance, 2)} absolute, or 50% of the planted rate,
              whichever is larger. Within tolerance:{" "}
              <strong>{((validation.summary?.label_noise_within_tolerance ?? 0) * 100).toFixed(0)}%</strong>.
            </div>
          </Card>
          <Card>
            <div className="text-xs uppercase tracking-wide text-slate-500">Noisy-label precision</div>
            <div className="mt-1 text-2xl font-semibold tabular">
              {formatNum(validation.summary?.label_noise_mean_precision, 2)}
            </div>
            <div className="text-xs text-slate-500">mean over 5/10/20% planted noise</div>
          </Card>
          <Card>
            <div className="text-xs uppercase tracking-wide text-slate-500">Noisy-label recall</div>
            <div className="mt-1 text-2xl font-semibold tabular">
              {formatNum(validation.summary?.label_noise_mean_recall, 2)}
            </div>
            <div className="text-xs text-slate-500">identified against the ground-truth manifest</div>
          </Card>
        </div>
      </Section>

      <Section title="Per-dataset quality checks" subtitle="Weighted 0–100 score per dataset with the failing checks called out.">
        <div className="space-y-4">
          {(datasetRubric.datasets ?? []).map((d: any) => (
            <Card key={d.dataset}>
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <h3 className="text-sm font-semibold text-slate-900">{d.dataset}</h3>
                  <ScoreBadge score={d.score} grade={d.grade} />
                </div>
                <span className="text-xs text-slate-500">
                  {d.n_passed}/{d.n_checks} checks pass · {d.failing_checks.length} need attention
                </span>
              </div>
              <div className="mt-3 grid gap-2 md:grid-cols-2 xl:grid-cols-3">
                {d.checks.map((c: any) => (
                  <div key={c.id} className="rounded-lg border border-slate-100 bg-slate-50/60 p-2.5">
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-xs font-medium text-slate-700">{c.name}</span>
                      <SeverityBadge severity={c.severity} />
                    </div>
                    <div className="mt-1 text-xs text-slate-500">
                      score {c.score.toFixed(2)}
                      {c.severity !== "info" ? ` · ${c.recommendation}` : ""}
                    </div>
                  </div>
                ))}
              </div>
            </Card>
          ))}
        </div>
      </Section>

      <Section title="Model-correctness checks" subtitle="Best model per dataset (highest mean CV accuracy).">
        <div className="grid gap-4 xl:grid-cols-2">
          {(modelRubric.models ?? []).map((m: any) => (
            <Card key={`${m.dataset}-${m.model}`}>
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div>
                  <h3 className="text-sm font-semibold text-slate-900">
                    {m.dataset} · {m.model}
                  </h3>
                  <span className="text-xs text-slate-500">{m.n_passed}/{m.n_checks} checks pass</span>
                </div>
                <ScoreBadge score={m.score} grade={m.grade} />
              </div>
              <table className="data mt-2 w-full text-xs">
                <tbody>
                  {m.checks.map((c: any) => (
                    <tr key={c.id}>
                      <td className="text-slate-700">{c.name}</td>
                      <td className="tabular">{c.score.toFixed(2)}</td>
                      <td>
                        <SeverityBadge severity={c.severity} />
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </Card>
          ))}
        </div>
      </Section>

      <Section title="Try the browser-side checker" subtitle="Runs the python-portable checks locally on your CSV.">
        <DatasetChecker config={config} />
      </Section>

      <Section title="Thresholds in force" subtitle="Loaded from configs/rubrics.yaml and exported with the results.">
        <Card className="overflow-x-auto">
          <table className="data w-full text-sm">
            <thead className="bg-slate-50">
              <tr>
                <th>Threshold</th>
                <th>Value</th>
              </tr>
            </thead>
            <tbody>
              {THRESHOLD_KEYS.map((key) => (
                <tr key={key}>
                  <td className="font-mono text-xs text-slate-600">{key}</td>
                  <td className="tabular">{String(config.dataset_quality.thresholds[key])}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      </Section>

      <Provenance provenance={datasetRubric.provenance} />
    </div>
  );
}
