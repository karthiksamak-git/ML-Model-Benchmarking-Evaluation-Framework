import { formatNum, loadData } from "@/lib/data";
import { Badge, Card, EmptyState, PageHeader, Provenance, Section } from "@/components/ui";

function ConfusionGrid({ labels, matrix }: { labels: number[]; matrix: number[][] }) {
  const max = Math.max(1, ...matrix.map((r) => Math.max(...r)));
  return (
    <table className="border-collapse text-xs">
      <thead>
        <tr>
          <th className="p-1 text-slate-400">true ↓ / pred →</th>
          {labels.map((l) => (
            <th key={l} className="p-1 font-medium text-slate-500">
              {l}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {matrix.map((row, i) => (
          <tr key={i}>
            <th className="p-1 text-right font-medium text-slate-500">{labels[i]}</th>
            {row.map((v, j) => {
              const intensity = v / max;
              return (
                <td
                  key={j}
                  className="p-1 text-center tabular"
                  style={{
                    background: i === j ? `rgba(0,114,178,${0.08 + 0.5 * intensity})` : `rgba(213,94,0,${0.05 + 0.6 * intensity})`,
                    color: intensity > 0.6 ? "white" : "#0f172a",
                    minWidth: 30,
                  }}
                  title={`${v} samples`}
                >
                  {v}
                </td>
              );
            })}
          </tr>
        ))}
      </tbody>
    </table>
  );
}

export default function ErrorsPage() {
  const errors = loadData("error_analysis.json");
  const gen = loadData("generalization.json");
  const results = errors.results ?? [];
  const curves = gen.learning_curves ?? [];
  const robustness = gen.robustness ?? [];
  const curveDatasets = [...new Set(curves.map((c: any) => c.dataset))];

  return (
    <div>
      <PageHeader
        title="Error analysis & generalization"
        lead={
          <>
            Per-class metrics, confusion structure, confident errors, error clusters, calibration, slice metrics,
            learning curves and robustness under Gaussian noise and covariate shift. The findings text is
            generated from the numbers in these tables (no templated claims).
          </>
        }
      />

      <Section title="Findings" subtitle="Generated by analysis/report.py from real predictions.">
        <Card>
          <pre className="whitespace-pre-wrap text-xs leading-relaxed text-slate-700">{errors.findings_markdown}</pre>
        </Card>
      </Section>

      <Section title="Per-dataset errors" subtitle="Best model per dataset on the shared first split.">
        {results.length === 0 ? (
          <EmptyState>No analysis exported yet.</EmptyState>
        ) : (
          <div className="space-y-5">
            {results.map((r: any) => (
              <Card key={r.dataset}>
                <div className="flex flex-wrap items-end justify-between gap-2">
                  <div>
                    <h3 className="text-sm font-semibold text-slate-900">
                      {r.dataset} · {r.model}
                    </h3>
                    <p className="text-xs text-slate-500">
                      accuracy {formatNum(r.accuracy, 4)} · ECE {formatNum(r.calibration?.ece, 4)} · {" "}
                      {r.n_test} test samples
                    </p>
                  </div>
                  <Badge tone="blue">{r.error_clusters?.n_errors ?? 0} errors</Badge>
                </div>

                <div className="mt-4 grid gap-5 lg:grid-cols-2">
                  <div className="overflow-x-auto">
                    <ConfusionGrid labels={r.labels} matrix={r.confusion_matrix} />
                  </div>
                  <div>
                    <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-500">Per class</h4>
                    <table className="data mt-1 w-full text-xs">
                      <thead>
                        <tr>
                          <th>Class</th>
                          <th>Precision</th>
                          <th>Recall</th>
                          <th>F1</th>
                          <th>Support</th>
                        </tr>
                      </thead>
                      <tbody>
                        {r.per_class.map((c: any) => (
                          <tr key={c.class}>
                            <td className="font-medium text-slate-800">{c.class}</td>
                            <td className="tabular">{formatNum(c.precision, 3)}</td>
                            <td className={`tabular ${c.recall < 0.7 ? "font-semibold text-rose-700" : ""}`}>
                              {formatNum(c.recall, 3)}
                            </td>
                            <td className="tabular">{formatNum(c.f1, 3)}</td>
                            <td className="tabular">{c.support}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                    {r.most_confused_pairs?.length ? (
                      <p className="mt-2 text-xs text-slate-500">
                        Most confused: true {r.most_confused_pairs[0].true} → predicted{" "}
                        {r.most_confused_pairs[0].predicted} ({r.most_confused_pairs[0].count} cases).
                      </p>
                    ) : null}
                  </div>
                </div>

                <div className="mt-4 grid gap-5 lg:grid-cols-3">
                  <div>
                    <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-500">
                      Top confident errors
                    </h4>
                    <table className="data mt-1 w-full text-xs">
                      <thead>
                        <tr>
                          <th>#</th>
                          <th>True</th>
                          <th>Pred.</th>
                          <th>Conf.</th>
                        </tr>
                      </thead>
                      <tbody>
                        {(r.top_confident_errors ?? []).slice(0, 8).map((e: any) => (
                          <tr key={e.index}>
                            <td className="tabular text-slate-500">{e.index}</td>
                            <td className="tabular">{e.true}</td>
                            <td className="tabular">{e.predicted}</td>
                            <td className="tabular">{formatNum(e.confidence, 3)}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                  <div>
                    <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-500">
                      Error clusters
                    </h4>
                    <ul className="mt-1 space-y-1 text-xs text-slate-600">
                      {(r.error_clusters?.clusters ?? []).map((c: any) => (
                        <li key={c.cluster} className="rounded-lg bg-slate-50 p-2">
                          <span className="font-medium text-slate-800">Cluster {c.cluster}</span> · {c.n} errors (
                          {(c.share * 100).toFixed(0)}%) ·{" "}
                          {c.defining_features.map((f: any) => `${f.feature} z=${f.mean_z}`).join(", ")}
                        </li>
                      ))}
                      {!r.error_clusters?.clusters?.length ? <li className="text-slate-400">No clusters.</li> : null}
                    </ul>
                  </div>
                  <div>
                    <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-500">Weakest slices</h4>
                    <ul className="mt-1 space-y-1 text-xs text-slate-600">
                      {[...(r.slices ?? [])]
                        .sort((a: any, b: any) => a.accuracy - b.accuracy)
                        .slice(0, 4)
                        .map((s: any, i: number) => (
                          <li key={i} className="rounded-lg bg-slate-50 p-2">
                            {s.feature} q{s.quartile} · accuracy {formatNum(s.accuracy, 3)} (n={s.n})
                          </li>
                        ))}
                      {!r.slices?.length ? <li className="text-slate-400">No slice metrics.</li> : null}
                    </ul>
                  </div>
                </div>

                <div className="mt-4">
                  <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-500">
                    Reliability (ECE {formatNum(r.calibration?.ece, 4)})
                  </h4>
                  <div className="mt-2 flex items-end gap-1" aria-label="reliability diagram">
                    {(r.calibration?.bins ?? []).map((b: any) => (
                      <div key={`${b.bin_low}`} className="flex-1" title={`conf ${b.mean_confidence.toFixed(2)} · acc ${b.accuracy.toFixed(2)} · n=${b.count}`}>
                        <div className="relative h-20 rounded-sm bg-slate-100">
                          <div
                            className="absolute bottom-0 w-full rounded-sm bg-blue-600/70"
                            style={{ height: `${Math.max(2, b.accuracy * 100)}%` }}
                          />
                        </div>
                        <div className="mt-1 text-center text-[9px] text-slate-400">
                          {b.mean_confidence.toFixed(1)}
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              </Card>
            ))}
          </div>
        )}
      </Section>

      <Section title="Learning curves" subtitle="Accuracy vs fraction of each training fold used.">
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {curveDatasets.map((ds) => {
            const rows = curves.filter((c: any) => c.dataset === ds);
            const fractions = [...new Set(rows.map((r: any) => r.fraction))].sort((a: any, b: any) => a - b);
            return (
              <Card key={String(ds)}>
                <h3 className="text-sm font-semibold text-slate-900">{String(ds)}</h3>
                <table className="data mt-2 w-full text-xs">
                  <thead>
                    <tr>
                      <th>Train fraction</th>
                      <th>Mean accuracy</th>
                      <th>Points</th>
                    </tr>
                  </thead>
                  <tbody>
                    {fractions.map((f: any) => {
                      const subset = rows.filter((r: any) => r.fraction === f);
                      const mean = subset.reduce((s: number, r: any) => s + r.accuracy, 0) / subset.length;
                      return (
                        <tr key={f}>
                          <td className="tabular">{(f * 100).toFixed(0)}%</td>
                          <td className="tabular">{formatNum(mean, 4)}</td>
                          <td className="tabular text-slate-400">{subset.length}</td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </Card>
            );
          })}
        </div>
      </Section>

      <Section title="Robustness" subtitle="Accuracy drop under Gaussian feature noise (std multiples) and covariate shift.">
        <Card className="overflow-x-auto">
          <table className="data w-full text-sm">
            <thead className="bg-slate-50">
              <tr>
                <th>Dataset</th>
                <th>Perturbation</th>
                <th>Level</th>
                <th>Accuracy</th>
                <th>Drop</th>
              </tr>
            </thead>
            <tbody>
              {robustness.map((r: any, i: number) => (
                <tr key={i}>
                  <td>{r.dataset}</td>
                  <td>{r.kind}</td>
                  <td className="tabular">{r.level}</td>
                  <td className="tabular">{formatNum(r.accuracy, 4)}</td>
                  <td className={`tabular ${r.drop > 0.1 ? "font-semibold text-rose-700" : ""}`}>
                    {formatNum(r.drop, 4)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      </Section>

      <Provenance provenance={errors.provenance} />
    </div>
  );
}
